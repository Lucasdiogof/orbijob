#!/usr/bin/env python3
"""Generates app/lib/core/design/tokens/app_colors.dart from docs/design/identity/c-minimal/tokens.json."""
import json, pathlib
HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[3]
SRC = ROOT / 'docs/design/identity/c-minimal/tokens.json'
DST = ROOT / 'app/lib/core/design/tokens/app_colors.dart'

def render():
    tokens = json.loads(SRC.read_text())['color']
    keys = list(tokens['light'].keys()); assert list(tokens['dark'].keys()) == keys
    hexc = lambda h: 'Color(0xFF' + h.lstrip('#').upper() + ')'
    nl = '\n'
    fields = ''.join(f'  final Color {k};{nl}' for k in keys)
    ctor = ''.join(f'    required this.{k},{nl}' for k in keys)
    copy_params = ''.join(f'    Color? {k},{nl}' for k in keys)
    copy_body = ''.join(f'      {k}: {k} ?? this.{k},{nl}' for k in keys)
    lerp = ''.join(f'      {k}: Color.lerp({k}, other.{k}, t)!,{nl}' for k in keys)
    inst = lambda mode: ''.join(f'      {k}: {hexc(v)},{nl}' for k, v in tokens[mode].items())
    roles = ', '.join(repr(k) for k in keys)
    cases = ''.join(f"    {k!r} => {k},{nl}" for k in keys)
    return f'''// GENERATED by docs/design/identity/build/dart_tokens.py from docs/design/identity/c-minimal/tokens.json.
// Do not edit by hand: change the tokens source and regenerate. A test compares this file with the JSON.
import 'package:flutter/material.dart';

@immutable
class AppColors extends ThemeExtension<AppColors> {{
  const AppColors({{
{ctor}  }});

{fields}
  static const AppColors light = AppColors(
{inst('light')}  );

  static const AppColors dark = AppColors(
{inst('dark')}  );

  @override
  AppColors copyWith({{
{copy_params}  }}) {{
    return AppColors(
{copy_body}    );
  }}

  @override
  AppColors lerp(ThemeExtension<AppColors>? other, double t) {{
    if (other is! AppColors) return this;
    return AppColors(
{lerp}    );
  }}

  /// Every role name, in declaration order (used by token tests).
  static const List<String> roles = <String>[{roles}];

  Color byName(String role) => switch (role) {{
{cases}    _ => throw ArgumentError.value(role, 'role'),
  }};
}}
'''

if __name__ == '__main__':
    DST.parent.mkdir(parents=True, exist_ok=True); DST.write_text(render()); print('dart tokens ok', DST.relative_to(ROOT))
