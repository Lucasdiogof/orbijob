#!/usr/bin/env node
// Builds app/lib/features/search/domain/occupation_labels.g.dart from ESCO (European Skills, Competences, Qualifications and Occupations,
// © European Union, https://esco.ec.europa.eu, CC BY 4.0). Reproducible:
//   node scripts/build-occupations.mjs <details.json>
// <details.json> is the per-occupation export made with the public ESCO API (`/search?type=occupation` + `/resource/occupation`), keyed by
// occupation URI: { en, pref: {lang: label}, alt: {lang: [labels]}, isco: [...], code }.
//
// What is kept, and why (false equivalences are worse than missing ones):
// * PREFERRED labels in every language kept, split on "/" (gender forms: "Physiotherapeut/Physiotherapeutin" -> both).
// * ALTERNATIVE labels only when they contain the first word of a preferred label of the same language (5+ characters): ESCO lists related
//   jobs among alternatives ("terapeuta ocupacional" under physiotherapist in Portuguese); they are dropped.
// * Labels of 1-4 words, 4+ characters, without parentheses or commas (job titles are short; long descriptive labels never appear in titles).
// * A label shared by more than 6 occupations is too generic to identify one ("assistant", "manager") and is dropped everywhere.
// * Labels are lower-cased; accents are kept (titles are matched as written); the app compares queries accent-insensitively.
import { readFileSync, writeFileSync } from 'node:fs';

const LANGS = ['en', 'pt', 'es', 'de', 'sv', 'nl', 'fr']; // the languages of the catalogue (EN, DE, SV, NL, FR) and of the app (PT, ES, EN)
const details = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const clean = (s) => s.toLowerCase().replace(/\s+/g, ' ').trim();
const fold = (s) => s.normalize('NFD').replace(/[̀-ͯ]/g, '');
const ok = (l) => l.length >= 4 && l.split(' ').length <= 4 && !/[(),;:"«»]/.test(l) && !/\d/.test(l);
const split = (l) => l.split('/').map(clean).filter(Boolean);

const PER_LANG = 3; // at most this many names per language and occupation (preferred first): enough to recognise the title, small enough for a filter
const groups = [];
for (const [uri, d] of Object.entries(details)) {
  const labels = [];
  for (const lang of LANGS) {
    const own = [];
    const prefs = d.pref?.[lang] ? split(d.pref[lang]) : [];
    for (const p of prefs) if (ok(p)) own.push(p);
    const heads = prefs.map((p) => fold(p.split(' ')[0])).filter((h) => h.length >= 5).map((h) => h.slice(0, Math.min(h.length, 8)));
    for (const a of d.alt?.[lang] ?? []) {
      for (const l of split(a)) if (ok(l) && heads.some((h) => fold(l).includes(h))) own.push(l);
    }
    for (const l of [...new Set(own)].slice(0, PER_LANG)) if (!labels.includes(l)) labels.push(l);
  }
  if (labels.length >= 2) groups.push({ uri, isco: String(d.code ?? '').slice(0, 4) || (d.isco?.[0] ?? ''), en: clean(d.en ?? ''), labels });
}
// A label that is the PREFERRED name of exactly one occupation belongs to it alone ("electrician" is the occupation Electrician, and only a related
// alternative of "electrical mechanic"), and is never dropped as generic. Any other label shared by many occupations does not identify one.
const owner = new Map();
for (const g of groups) {
  const d = details[g.uri];
  for (const lang of LANGS) for (const p of d.pref?.[lang] ? split(d.pref[lang]) : []) {
    if (!owner.has(p)) owner.set(p, new Set());
    owner.get(p).add(g.uri);
  }
}
const ownedBy = (l) => (owner.get(l)?.size === 1 ? [...owner.get(l)][0] : null);
const uses = new Map();
for (const g of groups) for (const l of g.labels) uses.set(l, (uses.get(l) ?? 0) + 1);
for (const g of groups) g.labels = g.labels.filter((l) => (ownedBy(l) ? ownedBy(l) === g.uri : uses.get(l) <= 6));
const kept = groups.filter((g) => g.labels.length >= 2).sort((a, b) => a.en.localeCompare(b.en));

const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\$/g, '\\$')}'`;
const out = [
  '// GENERATED by scripts/build-occupations.mjs from ESCO (European Skills, Competences, Qualifications and Occupations),',
  '// © European Union, https://esco.ec.europa.eu, licensed under CC BY 4.0. Labels filtered as documented in that script. Do not edit by hand.',
  '// ignore_for_file: lines_longer_than_80_chars',
  '',
  "/// One ESCO occupation: its ISCO-08 unit group and the names it is known by in the languages of the catalogue.",
  'class OccupationLabels {',
  '  const OccupationLabels(this.isco, this.labels);',
  '  final String isco;',
  '  final List<String> labels;',
  '}',
  '',
  `/// ${kept.length} occupations.`,
  'const escoOccupations = <OccupationLabels>[',
  ...kept.map((g) => `  OccupationLabels(${q(g.isco)}, [${g.labels.map(q).join(', ')}]),`),
  '];',
  '',
];
writeFileSync(new URL('../app/lib/features/search/domain/occupation_labels.g.dart', import.meta.url), out.join('\n'));
console.log(`occupations in: ${Object.keys(details).length}, kept: ${kept.length}, labels: ${kept.reduce((n, g) => n + g.labels.length, 0)}`);
