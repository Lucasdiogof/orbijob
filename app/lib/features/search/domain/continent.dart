  /// Region words a source may write that belong to this continent and no other (EMEA spans two, so it matches none).
  final List<String> regions;

  /// The continent of a country code, or null for an unknown or non-geographic code.
  static Continent? ofCountry(String? code) {
    final c = code?.trim().toUpperCase();
    if (c == null) return null;
    for (final k in Continent.values) {
      if (k.countries.contains(c)) return k;
    }
    return null;
  }

  /// PostgREST `or=(...)` body: the job's country is in the continent, or the source names an eligible country or
  /// region of it. Only ASCII codes and region words, so the filter structure cannot be altered.
  String get orFilter {
    final codes = (countries.toList()..sort()).join(',');
    final withRegions = [...(countries.toList()..sort()), ...regions].join(',');
    return 'country.in.($codes),geo_restrictions.ov.{$withRegions}';
  }
